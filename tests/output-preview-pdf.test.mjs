import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(new URL(`../src/${path}`, import.meta.url), 'utf8')
const source = read('components/outputs/OutputPreview.vue')
assert.match(source, /<FilePreview :source="source"/)
assert.match(source, /props.load\(item, \{ signal \}\)/)
assert.match(source, /props.contextKey/)
const shared = read('components/preview/FilePreview.vue')
assert.match(shared, /<PdfDocumentPreview v-else-if="kind === 'pdf'" :blob="blob"/)
assert.doesNotMatch(shared, /<iframe|v-html|download=/)
const lifecycle = read('composables/useFilePreview.js')
assert.match(lifecycle, /controller\?\.abort\(\)/)
assert.match(lifecycle, /URL.revokeObjectURL/)
assert.match(lifecycle, /onBeforeUnmount\(clear\)/)
assert.match(lifecycle, /current !== generation/)
assert.doesNotMatch(source, /selectedPartIndex|MAX_PREVIEW_BYTES/)
console.log('PDF uses shared original Blob viewer and cleanup boundary')
